// Writes docs/architecture-graph.md from the real import graph, one node per workspace package.
// With --check it fails instead when the committed graph no longer matches the code.
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const target = new URL('../docs/architecture-graph.md', import.meta.url)
const sourceFolders = ['packages', 'apps', 'tools']
  .flatMap((group) => readdirSync(root + group).map((name) => `${group}/${name}/src`))
  .filter((folder) => existsSync(root + folder))
const mermaid = execFileSync(
  `${root}node_modules/.bin/depcruise`,
  [
    ...sourceFolders,
    'eval/runner/src',
    '--config',
    '.dependency-cruiser.cjs',
    '--include-only',
    '^(packages|apps|tools|eval)/',
    '--collapse',
    '^(packages|apps|tools|eval)/[^/]+',
    '--exclude',
    '\\.test\\.tsx?$',
    '--output-type',
    'mermaid',
  ],
  { encoding: 'utf8', cwd: root },
)
const page = [
  '# Architecture graph',
  '',
  'Generated by `pnpm architecture` from the import graph; `pnpm check` fails when it is out of',
  'date. Each arrow is "depends on". Rules for which arrows are allowed live in',
  '[.dependency-cruiser.cjs](../.dependency-cruiser.cjs).',
  '',
  '```mermaid',
  mermaid.trim(),
  '```',
  '',
].join('\n')

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== page) {
    process.stderr.write('docs/architecture-graph.md is out of date; run pnpm architecture\n')
    process.exit(1)
  }
} else {
  writeFileSync(target, page)
}
